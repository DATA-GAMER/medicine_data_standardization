def apply_force_rules(raw_name: str, common_name: str, abbr: str, category: str) -> Tuple[str, str, str]:
    """强制规则匹配：精确 → 前缀 → 包含。宽泛规则不覆盖精确规则。"""
    key = normalize_for_force_map(raw_name)

    # ── 排除词（含这些词的项目一律不走宽泛匹配）──
    _EXCLUDE_WORDS = {"耐量", "负荷", "试验", "激发", "抗体", "受体", "酶", "培养", "释放"}

    # ── 1) 精确匹配优先 ──
    cn = FORCE_COMMON_NAME_MAP.get(key)
    ab = FORCE_ABBR_MAP.get(key)
    cat = FORCE_CATEGORY_MAP.get(key)
    if cn is not None and ab is not None and cat is not None:
        return cn, ab, cat

    # ── 2) 前缀匹配 ──
    if not any(w in key for w in _EXCLUDE_WORDS):
        for prefix, (p_cn, p_abbr, p_cat) in FORCE_PREFIX_RULES.items():
            if key.startswith(prefix):
                return p_cn, p_abbr, p_cat

    # ── 3) 包含匹配 ──
    if not any(w in key for w in _EXCLUDE_WORDS):
        for pattern, (p_cn, p_abbr, p_cat) in FORCE_CONTAINS_RULES.items():
            if pattern in key:
                return p_cn, p_abbr, p_cat

    # ── 4) 部分命中（精确匹配未全覆盖三项）──
    if cn is not None:
        common_name = cn
    if ab is not None:
        abbr = ab
    if cat is not None:
        category = cat
    return common_name, abbr, category


def is_fully_covered_by_force_rules(raw_name: str) -> bool:
    """A 方案预检：三项是否全部有强制规则覆盖（与 apply_force_rules 逻辑一致）。"""
    key = normalize_for_force_map(raw_name)
    _EXCLUDE_WORDS = {"耐量", "负荷", "试验", "激发", "抗体", "受体", "酶", "培养", "释放"}

    # 1) 精确匹配全覆盖
    if (key in FORCE_COMMON_NAME_MAP
            and key in FORCE_ABBR_MAP
            and key in FORCE_CATEGORY_MAP):
        return True

    if any(w in key for w in _EXCLUDE_WORDS):
        return False

    # 2) 前缀匹配覆盖
    if any(key.startswith(p) for p in FORCE_PREFIX_RULES):
        return True

    # 3) 包含匹配覆盖
    if any(p in key for p in FORCE_CONTAINS_RULES):
        return True

    return False


# ---- JSON 提取 ----

def extract_json(text: str) -> dict:
    """从模型返回中提取 JSON，多层兜底。"""
    text = str(text).strip()

    # 去除可能的 markdown 代码块
    text = re.sub(r"^```(?:json)?\s*", "", text)
    text = re.sub(r"\s*```$", "", text)

    # 直接解析
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        pass

    # 正则提取第一个完整 JSON 对象
    match = re.search(r"\{.*\}", text, flags=re.S)
    if match:
        try:
            return json.loads(match.group(0))
        except json.JSONDecodeError:
            pass

    # 尝试修复常见错误：尾部多余逗号
    try:
        fixed = re.sub(r",\s*([}\]])", r"\1", text)
        return json.loads(fixed)
    except json.JSONDecodeError:
        pass

    raise ValueError(f"无法从 API 返回内容中解析 JSON。返回内容前 500 字符：{text[:500]}")


