def is_bad_abbr(abbr: Any) -> bool:
    """简称/缩写不合格判断。"""
    if abbr is None:
        return True
    abbr = str(abbr).strip()
    if abbr.lower() in _BAD_ABBR_VALUES:
        return True
    if contains_chinese(abbr):
        return True
    if len(abbr) > 80 or "\n" in abbr or "\r" in abbr:
        return True
    if not re.search(r"[A-Za-z0-9Α-ω]", abbr):
        return True
    return False


