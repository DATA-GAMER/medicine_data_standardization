def load_cache(cache_path: Path) -> dict:
    if USE_CACHE and cache_path.exists():
        try:
            with open(cache_path, "r", encoding="utf-8") as f:
                cache = json.load(f)
            expected_meta = cache_metadata()
            actual_meta = cache.get("metadata", {})
            if actual_meta != expected_meta:
                print("缓存元数据与当前规则/Prompt/模型不一致，本次不复用旧缓存。")
                return {"metadata": expected_meta, "items": {}}
            if not isinstance(cache.get("items"), dict):
                print("缓存 items 结构无效，本次不复用旧缓存。")
                return {"metadata": expected_meta, "items": {}}
            return cache
        except (OSError, json.JSONDecodeError) as exc:
            print(f"缓存文件读取失败，将重新创建缓存：{exc}")
    return {"metadata": cache_metadata(), "items": {}}


def save_cache(cache: dict, cache_path: Path):
    if not SAVE_CACHE:
        return
    cache_path.parent.mkdir(parents=True, exist_ok=True)
    cache["metadata"] = cache_metadata()
    temp_path = cache_path.with_suffix(cache_path.suffix + ".tmp")
    with open(temp_path, "w", encoding="utf-8") as f:
        json.dump(cache, f, ensure_ascii=False, indent=2)
        f.flush()
        os.fsync(f.fileno())
    temp_path.replace(cache_path)


