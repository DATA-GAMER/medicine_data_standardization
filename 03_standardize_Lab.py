def read_csv_safely(path: Path) -> pd.DataFrame:
    """用常见编码读取 CSV，不对名称做任何清洗。"""
    if not path.exists():
        raise FileNotFoundError(f"CSV 文件不存在：{path}")
    if not path.is_file():
        raise ValueError(f"CSV 路径不是文件：{path}")

    encodings = ["utf-8-sig", "utf-8", "gbk", "gb18030"]
    last_error: Optional[UnicodeDecodeError] = None
    for enc in encodings:
        try:
            return pd.read_csv(
                path, encoding=enc,
                dtype={"名称": str, "检验项目": str},
                keep_default_na=False,
                low_memory=False,
            )
        except UnicodeDecodeError as e:
            last_error = e
    raise RuntimeError(f"CSV 读取失败，请检查文件编码。最后一次错误：{last_error}")


def validate_input_df(df: pd.DataFrame, cohort_name: str) -> pd.DataFrame:
    """校验映射表输入，拒绝静默处理空名称或非法频数。"""
    # 兼容实际表头：检验项目 → 名称，出现次数 → 频数
    df = df.rename(columns={"检验项目": "名称", "出现次数": "频数"})

    required = {"名称", "频数"}
    missing = required.difference(df.columns)
    if missing:
        raise ValueError(f"[{cohort_name}] CSV 缺少列：{sorted(missing)}")

    result = df.copy()
    empty_name = result["名称"].astype(str).str.strip().eq("")
    if empty_name.any():
        rows = (result.index[empty_name] + 2).tolist()[:20]
        raise ValueError(f"[{cohort_name}] 存在空检验名称，CSV 行号示例：{rows}")

    frequency = pd.to_numeric(result["频数"], errors="coerce")
    invalid_frequency = frequency.isna() | (frequency < 0)
    if invalid_frequency.any():
        rows = (result.index[invalid_frequency] + 2).tolist()[:20]
        raise ValueError(f"[{cohort_name}] 频数必须为非负数，CSV 行号示例：{rows}")
    result["频数"] = frequency
    return result


