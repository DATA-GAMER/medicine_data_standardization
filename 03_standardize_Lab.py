def validate_api_response_items(
    items: Any,
    batch_records: List[Dict[str, Any]],
) -> Tuple[Dict[str, Dict[str, Any]], List[str]]:
    """校验返回条数、ID、必填字段。返回 (合格item_map, 失败id列表)。"""
    if not isinstance(items, list):
        raise ValueError("JSON 中 items 不是列表")
    if len(items) != len(batch_records):
        raise ValueError(
            f"API 返回条数 ({len(items)}) 与输入 ({len(batch_records)}) 不一致"
        )

    expected = {str(rec["id"]): rec for rec in batch_records}
    item_map: Dict[str, Dict[str, Any]] = {}
    failed_ids: List[str] = []

    for position, item in enumerate(items, start=1):
        if not isinstance(item, dict):
            raise ValueError(f"API 第 {position} 条不是 JSON 对象")
        item_id = str(item.get("id", ""))
        if not item_id:
            raise ValueError(f"API 第 {position} 条缺少 id")
        if item_id in item_map:
            raise ValueError(f"API 返回重复 id：{item_id}")
        item_map[item_id] = item

    if set(item_map.keys()) != set(expected):
        missing = sorted(set(expected).difference(item_map.keys()))
        extra = sorted(set(item_map.keys()).difference(expected))
        raise ValueError(f"API id 不一致，缺失={missing}，多余={extra}")

    for item_id, record in expected.items():
        item = item_map[item_id]
        if item.get("原始名称") != record["raw_name"]:
            failed_ids.append(item_id)
            continue
        common_name = str(item.get("通用名", "")).strip()
        abbr = str(item.get("简称/缩写", "")).strip()
        category = str(item.get("分类", "")).strip()
        if not common_name or is_bad_abbr(abbr) or category not in ALLOWED_SET:
            failed_ids.append(item_id)

    return item_map, failed_ids


def call_model_single(rec: Dict[str, Any]) -> Dict[str, str]:
    """单条调用模型（用于批量校验失败的个体重试）。"""
    batch = [rec]
    results = call_model_batch(batch)
    return results[0] if results else make_standard_item(
        raw_name=rec["raw_name"], common_name="", abbr="", category="其他",
    )


def call_model_batch(batch_records: List[Dict[str, Any]]) -> List[Dict[str, str]]:
    """调用模型处理一批检验名称。单条不合格只影响该条，不拖垮整批。"""

    user_payload = {"items": batch_records}
    user_content = (
        "请标准化以下检验项目。注意：禁止拆分，输出条数必须与输入条数一致。"
        "简称/缩写必须为英文缩写或 LOINC 风格英文短名，不能空白，不能含中文。\n"
        + json.dumps(user_payload, ensure_ascii=False)
    )

    # 指数退避重试
    for attempt in range(1, MAX_RETRIES + 1):
        try:
            response = get_api_client().chat.completions.create(
                model=MODEL_NAME,
                messages=[
                    {"role": "system", "content": SYSTEM_PROMPT},
                    {"role": "user", "content": user_content},
                ],
                temperature=0.0,
                response_format={"type": "json_object"},
                max_tokens=8000,
            )
            result_text = response.choices[0].message.content
            if not result_text or not result_text.strip():
                raise ValueError("API 返回 content 为空")
            data = extract_json(result_text)
            items = data.get("items", [])
            item_map, failed_ids = validate_api_response_items(items, batch_records)

            output_records = []
            for rec in batch_records:
                rec_id = str(rec["id"])
                if rec_id in failed_ids:
                    # 单条不合格，单独重试一次
                    print(f"  id={rec_id} 校验不合格，单独重试…")
                    output_records.append(call_model_single(rec))
                else:
                    raw_name = rec["raw_name"]
                    api_item = item_map.get(rec_id, {})
                    output_records.append(make_standard_item(
                        raw_name=raw_name,
                        common_name=api_item.get("通用名", ""),
                        abbr=api_item.get("简称/缩写", ""),
                        category=api_item.get("分类", "其他"),
                        mapping_source=f"API:{MODEL_NAME}",
                    ))

            return output_records

        except Exception as e:
            wait = min(2 ** (attempt - 1), 8) + random.uniform(0, 0.5)
            print(f"第 {attempt}/{MAX_RETRIES} 次调用失败：{e}，{wait:.1f}s 后重试…")
            if attempt < MAX_RETRIES:
                time.sleep(wait)

    # 全部失败：明确标记，后续不得写入成功缓存。
    print(f"该批次 {MAX_RETRIES} 次重试全部失败，已标记为待重试。")
    return [make_standard_item(
        raw_name=rec["raw_name"],
        common_name="",
        abbr="",
        category="其他",
        mapping_source=f"API:{MODEL_NAME}",
        mapping_status="API失败待重试",
        error_message="API调用或返回校验失败",
    ) for rec in batch_records]


def should_cache_item(item: Dict[str, str]) -> bool:
    """仅缓存真正完成映射的结果，避免失败占位污染缓存。"""
    return item.get("映射状态") == "已映射"


