def _clean_review_cell(value: Any) -> str:
    """把 Excel/CSV 单元格稳定转换为去空白字符串。"""
    if value is None or pd.isna(value):
        return ""
    if isinstance(value, pd.Timestamp):
        return value.date().isoformat()
    return str(value).strip()


def load_manual_review(review_path: Path = MANUAL_REVIEW_FILE) -> pd.DataFrame:
    """读取并严格校验人工复核表；空白决定视为“未处理”。"""
    if not review_path.exists():
        print(f"人工复核表尚不存在：{review_path}")
        return pd.DataFrame(columns=MANUAL_REVIEW_COLUMNS)

    suffix = review_path.suffix.lower()
    if suffix in {".xlsx", ".xls"}:
        with pd.ExcelFile(review_path) as workbook:
            sheet_name = (
                "人工复核"
                if "人工复核" in workbook.sheet_names
                else workbook.sheet_names[0]
            )
            review = pd.read_excel(
                workbook,
                sheet_name=sheet_name,
                dtype=str,
                keep_default_na=False,
            )
    elif suffix == ".csv":
        review = read_csv_safely(review_path)
    else:
        raise ValueError(f"人工复核表仅支持 xlsx/xls/csv：{review_path}")

    required = {"原始名称", "处理决定"}
    missing = required.difference(review.columns)
    if missing:
        raise ValueError(f"人工复核表缺少必需列：{sorted(missing)}")

    for column in MANUAL_REVIEW_COLUMNS:
        if column not in review:
            review[column] = ""
        review[column] = review[column].map(_clean_review_cell)

    review = review[MANUAL_REVIEW_COLUMNS]
    review = review[review["原始名称"].ne("")].copy()
    review.loc[review["处理决定"].eq(""), "处理决定"] = "未处理"

    invalid_decisions = sorted(
        set(review["处理决定"]).difference(MANUAL_REVIEW_DECISIONS)
    )
    if invalid_decisions:
        raise ValueError(
            f"人工复核表存在无效处理决定：{invalid_decisions}；"
            f"允许值={sorted(MANUAL_REVIEW_DECISIONS)}"
        )

    duplicated = review[review["原始名称"].duplicated(keep=False)]
    if not duplicated.empty:
        names = sorted(duplicated["原始名称"].unique())[:20]
        raise ValueError(f"人工复核表的原始名称必须唯一，重复示例：{names}")

    return review


def apply_manual_review(
    df: pd.DataFrame,
    review_path: Path = MANUAL_REVIEW_FILE,
    cohort_name: str = "全局",
) -> Tuple[pd.DataFrame, int]:
    """以原始名称为键应用人工复核；人工结果优先于缓存、API和普通规则。"""
    result = df.copy()
    review = load_manual_review(review_path)
    processed = review[review["处理决定"].ne("未处理")]
    if processed.empty:
        print(f"[{cohort_name}] 没有可应用的人工复核记录。")
        return result, 0

    if result["原始名称"].duplicated().any():
        raise ValueError(f"[{cohort_name}] 待回写映射表存在重复原始名称")

    index_by_name = {
        str(raw_name): index
        for index, raw_name in result["原始名称"].items()
    }
    unmatched: List[str] = []
    applied = 0

    for _, review_row in processed.iterrows():
        raw_name = review_row["原始名称"]
        target_index = index_by_name.get(raw_name)
        if target_index is None:
            unmatched.append(raw_name)
            continue

        decision = review_row["处理决定"]
        current_common = _clean_review_cell(result.at[target_index, "通用名"])
        current_abbr = _clean_review_cell(result.at[target_index, "简称/缩写"])
        current_category = _clean_review_cell(result.at[target_index, "分类"])

        if decision == "修正":
            manual_values = {
                "通用名": review_row["人工通用名"],
                "简称/缩写": review_row["人工简称/缩写"],
                "分类": review_row["人工分类"],
                "LOINC编码": review_row["人工LOINC编码"],
            }
            if not any(manual_values.values()):
                raise ValueError(
                    f"人工复核“{raw_name}”选择了修正，但未填写任何人工修正值"
                )
            new_common = manual_values["通用名"] or current_common
            new_abbr = manual_values["简称/缩写"] or current_abbr
            new_category = manual_values["分类"] or current_category
            if not new_common or new_common == "待补充":
                raise ValueError(f"人工复核“{raw_name}”的通用名不合格")
            if is_bad_abbr(new_abbr):
                raise ValueError(
                    f"人工复核“{raw_name}”的简称/缩写不合格：{new_abbr!r}"
                )
            if new_category not in ALLOWED_SET:
                raise ValueError(
                    f"人工复核“{raw_name}”的分类不在允许列表：{new_category!r}"
                )
            result.at[target_index, "通用名"] = new_common
            result.at[target_index, "简称/缩写"] = new_abbr
            result.at[target_index, "分类"] = new_category
            if manual_values["LOINC编码"]:
                result.at[target_index, "LOINC编码"] = manual_values["LOINC编码"]
                result.at[target_index, "LOINC映射状态"] = "已人工复核"
            for key, value in extract_lab_attributes(raw_name, new_common).items():
                result.at[target_index, key] = value
            mapping_status = "已人工复核"
        elif decision in {"保持原值", "接受简称歧义"}:
            if (
                not current_common
                or current_common == "待补充"
                or is_bad_abbr(current_abbr)
                or current_category not in ALLOWED_SET
            ):
                raise ValueError(
                    f"人工复核“{raw_name}”当前映射不完整，不能选择“{decision}”，"
                    "请改为“修正”并填写有效值"
                )
            mapping_status = (
                "已人工确认歧义" if decision == "接受简称歧义" else "已人工复核"
            )
        elif decision == "排除":
            mapping_status = "人工排除"
        else:
            raise ValueError(f"不支持的人工处理决定：{decision}")

        result.at[target_index, "映射来源"] = "人工复核"
        result.at[target_index, "映射状态"] = mapping_status
        result.at[target_index, "冲突类型"] = ""
        result.at[target_index, "错误信息"] = ""
        result.at[target_index, "人工处理决定"] = decision
        result.at[target_index, "复核人"] = review_row["复核人"]
        result.at[target_index, "复核日期"] = (
            review_row["复核日期"] or datetime.now().date().isoformat()
        )
        result.at[target_index, "复核备注"] = review_row["复核备注"]
        if ADD_REVIEW_COLUMN:
            result.at[target_index, "简称是否需复核"] = "否"
        applied += 1

    if unmatched:
        print(
            f"[{cohort_name}] 提示：人工复核表中有 {len(unmatched)} 个名称"
            f"不在本次数据中，示例：{unmatched[:10]}"
        )
    print(f"[{cohort_name}] 已应用人工复核：{applied} 条")
    return result, applied


def build_manual_review_template(review_report: pd.DataFrame) -> pd.DataFrame:
    """把剩余待复核结果转换为独立、可审计的人工录入表。"""
    source_map = {
        "当前通用名": "通用名",
        "当前简称/缩写": "简称/缩写",
        "当前分类": "分类",
        "当前冲突类型": "冲突类型",
        "当前映射状态": "映射状态",
        "当前映射来源": "映射来源",
        "当前错误信息": "错误信息",
    }
    template = pd.DataFrame(index=review_report.index)
    template["原始名称"] = review_report["原始名称"].astype(str)
    for target, source in source_map.items():
        template[target] = review_report.get(source, "")
    for column in MANUAL_REVIEW_COLUMNS:
        if column not in template:
            template[column] = "未处理" if column == "处理决定" else ""
    return (
        template[MANUAL_REVIEW_COLUMNS]
        .drop_duplicates(subset=["原始名称"], keep="last")
        .sort_values(["当前映射状态", "当前冲突类型", "原始名称"])
        .reset_index(drop=True)
    )


def ensure_manual_review_template(
    review_report: pd.DataFrame,
    review_path: Path = MANUAL_REVIEW_FILE,
) -> None:
    """仅在文件不存在时创建模板，绝不覆盖已经填写的人工结论。"""
    if review_path.exists():
        known = load_manual_review(review_path)
        known_names = set(known["原始名称"])
        new_count = int(
            (~review_report["原始名称"].astype(str).isin(known_names)).sum()
        )
        if new_count:
            print(
                f"人工复核表保持不变；另有 {new_count} 个新待复核名称，"
                "请从 Lab_review_required.csv 补充到人工复核表。"
            )
        return
    template = build_manual_review_template(review_report)
    atomic_write_excel(template, review_path)
