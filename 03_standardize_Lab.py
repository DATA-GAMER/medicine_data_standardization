def extract_lab_attributes(raw_name: str, common_name: str) -> Dict[str, str]:
    """从名称中提取不应在通用名归一化时丢失的临床属性。"""
    text = f"{raw_name} {common_name}"
    normalized_raw = normalize_for_force_map(raw_name)

    if "24小时尿" in normalized_raw or "24h尿" in normalized_raw:
        specimen = "24小时尿"
    elif "尿沉渣" in text:
        specimen = "尿沉渣"
    elif (
        "尿液" in text
        or normalized_raw.startswith("尿尿")
        or normalized_raw.startswith("尿酸碱度")
        or (
            normalized_raw.startswith("尿")
            and not normalized_raw.startswith(("尿酸", "尿素"))
        )
    ):
        specimen = "尿液"
    else:
        specimen_rules = [
            ("动脉血", "动脉血"),
            ("静脉血", "静脉血"),
            ("末梢血", "末梢血"),
            ("全血", "全血"),
            ("血清", "血清"),
            ("血浆", "血浆"),
            ("脑脊液", "脑脊液"),
            ("粪", "粪便"),
        ]
        specimen = next(
            (label for keyword, label in specimen_rules if keyword in text),
            "未明确",
        )

    property_rules = [
        ("排泄率", "排泄率"),
        ("总量", "总量"),
        ("浓度", "浓度"),
        ("比值", "比值"),
        ("百分比", "百分比"),
        ("计数", "计数"),
        ("定性", "定性"),
        ("定量", "定量"),
        ("活性", "活性"),
        ("效价", "效价"),
        ("核型", "核型"),
    ]
    measurement_property = next(
        (label for keyword, label in property_rules if keyword in text),
        "未明确",
    )

    conditions: List[str] = []
    if "24小时" in text or "24h" in text.lower():
        conditions.append("24小时收集")
    for keyword in ("空腹", "餐后", "随机", "OGTT", "负荷"):
        if keyword.lower() in text.lower():
            conditions.append(keyword)
    for value, unit in re.findall(
        r"(?<!24)(\d+(?:\.\d+)?)\s*(h|小时|min|分钟)",
        text,
        flags=re.I,
    ):
        if value == "24" and specimen == "24小时尿":
            continue
        conditions.append(f"{value}{unit}")
    collection_condition = "；".join(dict.fromkeys(conditions)) or "未明确"

    method_keywords = [
        "干化学", "镜检", "酶法", "电极法", "免疫比浊法",
        "胶乳增强免疫比浊法", "化学发光法", "间接免疫荧光法",
        "免疫印迹法", "流式微球法",
    ]
    methods = [method for method in method_keywords if method in text]

    modifiers = [value for value in ("超敏", "急诊", "床旁") if value in text]

    return {
        "标本类型": specimen,
        "检测属性": measurement_property,
        "采集条件": collection_condition,
        "方法学": "；".join(methods) or "未明确",
        "临床修饰": "；".join(modifiers) or "无",
    }


def make_standard_item(
    raw_name: str,
    common_name: str,
    abbr: str,
    category: str,
    mapping_source: str = "API",
    mapping_status: str = "已映射",
    error_message: str = "",
) -> Dict[str, str]:
    """构建一条标准化记录，应用强制规则并标记是否需要复核。"""
    common_name = (common_name or "").strip() or "待补充"
    abbr = (abbr or "").strip()
    category = (category or "").strip()
    if category not in ALLOWED_SET:
        category = "其他"

    # 应用强制规则（这是唯一调用点）
    force_hit = is_fully_covered_by_force_rules(raw_name)
    common_name, abbr, category = apply_force_rules(raw_name, common_name, abbr, category)
    if force_hit:
        mapping_source = "强制规则"

    # 简称最终校验
    bad_abbr = is_bad_abbr(abbr)
    need_review = "是" if bad_abbr else "否"
    if bad_abbr:
        abbr = "LOINC ShortName Required"
    if category not in ALLOWED_SET:
        category = "其他"
        mapping_status = "待复核"
    if common_name == "待补充" or bad_abbr:
        if not mapping_status.startswith("API失败"):
            mapping_status = "待复核"

    item: Dict[str, str] = {
        "原始名称": raw_name,
        "通用名": common_name,
        "简称/缩写": abbr,
        "分类": category,
        **extract_lab_attributes(raw_name, common_name),
        "LOINC编码": "",
        "LOINC映射状态": "待人工映射",
        "映射来源": mapping_source,
        "映射状态": mapping_status,
        "冲突类型": "",
        "错误信息": error_message,
        "规则版本": RULES_VERSION,
        "人工处理决定": "",
        "复核人": "",
        "复核日期": "",
        "复核备注": "",
    }
    if ADD_REVIEW_COLUMN:
        item["简称是否需复核"] = need_review

    return item


