def validate_consistency(df: pd.DataFrame, cohort_name: str) -> pd.DataFrame:
    """同名多值冲突自动统一到第一个值（排序后第一个），不再标记人工复核。"""
    result = df.copy()
    if "冲突类型" not in result:
        result["冲突类型"] = ""
    if "映射状态" not in result:
        result["映射状态"] = "已映射"

    resolved_mask = result["映射状态"].isin(MANUAL_RESOLVED_STATUSES)
    # 排除占位符和失败项目，避免污染冲突检测
    excluded_mask = (
        result["映射状态"].eq("人工排除")
        | result["映射状态"].astype(str).str.startswith("API失败")
        | result["通用名"].eq("待补充")
        | result["简称/缩写"].map(is_bad_abbr)
    )
    active = result.loc[~excluded_mask]
    auto_resolved = 0

    def resolve_first(mask: pd.Series, column: str, first_value) -> int:
        """把未人工解决、未排除且值不同的行统一到 first_value，返回改写行数。"""
        targets = mask & ~resolved_mask & ~excluded_mask
        targets &= result[column].astype(str).str.strip().ne(str(first_value).strip())
        if not targets.any():
            return 0
        result.loc[targets, column] = first_value
        result.loc[targets, "映射来源"] = "一致性统一"
        if ADD_REVIEW_COLUMN:
            result.loc[targets, "简称是否需复核"] = "否"
        return int(targets.sum())

    # 同一通用名对应多个分类 → 统一为第一个分类
    category_counts = active.groupby("通用名")["分类"].nunique()
    for common_name in category_counts[category_counts > 1].index:
        active_mask = result["通用名"].eq(common_name) & ~excluded_mask
        values = sorted(result.loc[active_mask, "分类"].dropna().unique())
        first_value = values[0]
        if resolve_first(result["通用名"].eq(common_name), "分类", first_value):
            auto_resolved += 1
            print(f"  [unify] 「{common_name}」统一分类为：{first_value}")

    # 同一通用名对应多个简称 → 统一为第一个简称
    abbr_counts = active.groupby("通用名")["简称/缩写"].nunique()
    for common_name in abbr_counts[abbr_counts > 1].index:
        active_mask = result["通用名"].eq(common_name) & ~excluded_mask
        values = sorted(result.loc[active_mask, "简称/缩写"].dropna().unique())
        first_value = values[0]
        if resolve_first(result["通用名"].eq(common_name), "简称/缩写", first_value):
            auto_resolved += 1
            print(f"  [unify] 「{common_name}」统一简称为：{first_value}")

    # 同一简称对应多个通用名 → 统一为第一个通用名
    name_counts = active.groupby("简称/缩写")["通用名"].nunique()
    for abbr in name_counts[name_counts > 1].index:
        active_mask = result["简称/缩写"].eq(abbr) & ~excluded_mask
        values = sorted(result.loc[active_mask, "通用名"].dropna().unique())
        first_value = values[0]
        if resolve_first(result["简称/缩写"].eq(abbr), "通用名", first_value):
            auto_resolved += 1
            print(f"  [unify] 「{abbr}」统一通用名为：{first_value}")

    if auto_resolved == 0:
        print(f"[{cohort_name}] [OK] 一致性校验通过，无需统一。")
    else:
        print(
            f"[{cohort_name}] 已自动统一 {auto_resolved} 个冲突组（统一到第一个值），"
            f"不再标记人工复核。"
        )

    return result


def standardize_names(unique_names: List[str], cache_file: Path, label: str = "") -> Dict[str, Dict[str, str]]:
    """核心标准化 pipeline：输入一批唯一名称，返回 raw_name → 标准化 item 的映射。"""
    cache = load_cache(cache_file)
    cache_items: Dict[str, dict] = cache.get("items", {})

    standard_map: Dict[str, Dict[str, str]] = {}
    pending_records: List[Dict[str, Any]] = []
    force_hit_count = 0

    for idx, raw_name in enumerate(unique_names, start=1):
        key = hash_name(raw_name)
        cached = cache_items.get(key)

        if (
            USE_CACHE
            and cached
            and cached.get("原始名称") == raw_name
            and should_cache_item(cached)
        ):
            item = make_standard_item(
                raw_name=raw_name,
                common_name=cached.get("通用名", ""),
                abbr=cached.get("简称/缩写", ""),
                category=cached.get("分类", "其他"),
                mapping_source=cached.get("映射来源", "缓存"),
                mapping_status=cached.get("映射状态", "已映射"),
            )
            standard_map[raw_name] = item
            cache_items[key] = item.copy()
        elif is_fully_covered_by_force_rules(raw_name):
            item = make_standard_item(raw_name, "", "", "其他")
            standard_map[raw_name] = item
            cache_items[key] = item.copy()
            force_hit_count += 1
        else:
            pending_records.append({"id": idx, "raw_name": raw_name})

    prefix = f"[{label}] " if label else ""
    print(f"{prefix}缓存命中：{len(standard_map) - force_hit_count}，强制规则命中：{force_hit_count}，需要调用 API：{len(pending_records)}")

    if standard_map and SAVE_CACHE:
        save_cache(cache, cache_file)

    if pending_records:
        batches = list(chunk_list(pending_records, BATCH_SIZE))
        batch_iter = tqdm(batches, desc=f"{prefix}API 批次") if HAS_TQDM else batches

        for batch_idx, batch in enumerate(batch_iter, 1):
            if not HAS_TQDM:
                print(f"{prefix}正在处理第 {batch_idx}/{len(batches)} 批，本批 {len(batch)} 条...")

            batch_results = call_model_batch(batch)

            for item in batch_results:
                raw_name = item["原始名称"]
                standard_map[raw_name] = item
                if should_cache_item(item):
                    cache_items[hash_name(raw_name)] = item.copy()

            if SAVE_CACHE and (batch_idx % CACHE_SAVE_INTERVAL == 0):
                save_cache(cache, cache_file)

            time.sleep(SLEEP_SECONDS)

        if SAVE_CACHE:
            save_cache(cache, cache_file)
            print(f"{prefix}缓存已保存。")
    else:
        print(f"{prefix}全部项目均命中缓存，无需调用 API。")

    failed_count = sum(
        item.get("映射状态") == "API失败待重试"
        for item in standard_map.values()
    )
    if failed_count:
        print(f"{prefix}警告：{failed_count} 个项目 API 失败，未写入成功缓存。")

    return standard_map


def output_path_for_mode(path: Path) -> Path:
    """测试模式使用独立文件名，绝不覆盖正式映射表。"""
    if not TEST_MODE:
        return path
    return path.with_name(f"{path.stem}_test{path.suffix}")


def atomic_write_excel(df: pd.DataFrame, output_path: Path) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    temp_path = output_path.with_name(f"{output_path.stem}.tmp{output_path.suffix}")
    df.to_excel(temp_path, index=False, engine="openpyxl")
    temp_path.replace(output_path)


def atomic_write_csv(df: pd.DataFrame, output_path: Path) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    temp_path = output_path.with_name(f"{output_path.stem}.tmp{output_path.suffix}")
    df.to_csv(temp_path, index=False, encoding="utf-8-sig")
    temp_path.replace(output_path)


def apply_and_output(
    cfg: dict,
    standard_map: Dict[str, Dict[str, str]],
    df_input: Optional[pd.DataFrame] = None,
) -> None:
    """用全局 standard_map 为单个队列做合并、校验、输出。"""
    name = cfg["name"]
    input_path = Path(cfg["input"])
    output_path = output_path_for_mode(Path(cfg["output"]))

    print(f"\n{'='*60}")
    print(f"队列：{name}")
    print(f"模式：{'测试' if TEST_MODE else '全量'}")
    print(f"输出：{output_path}")
    print(f"{'='*60}")

    if df_input is None:
        df_input = validate_input_df(read_csv_safely(input_path), name)
    if TEST_MODE:
        df_work = df_input.head(TEST_N).copy()
    else:
        df_work = df_input.copy()

    # ---- 构建映射表 ----
    df_std = pd.DataFrame(list(standard_map.values()))
    df_std = df_std.drop_duplicates(subset=["原始名称"], keep="last")

    # ---- FORCE_BY_COMMON_NAME 后处理 ----
    forced_values = df_std["通用名"].map(FORCE_BY_COMMON_NAME)
    manual_mask = df_std["映射状态"].isin(MANUAL_RESOLVED_STATUSES)
    forced_mask = forced_values.notna() & ~manual_mask
    forced_abbr = forced_values[forced_mask].map(lambda value: value[0])
    forced_cat = forced_values[forced_mask].map(lambda value: value[1])
    changed_mask = forced_mask.copy()
    changed_mask.loc[forced_mask] = (
        df_std.loc[forced_mask, "简称/缩写"].ne(forced_abbr)
        | df_std.loc[forced_mask, "分类"].ne(forced_cat)
    )
    force_applied = int(changed_mask.sum())
    if force_applied:
        df_std.loc[forced_mask, "简称/缩写"] = forced_abbr
        df_std.loc[forced_mask, "分类"] = forced_cat
        df_std.loc[changed_mask, "映射来源"] = "通用名强制规则"
        if ADD_REVIEW_COLUMN:
            df_std.loc[changed_mask, "简称是否需复核"] = "否"
    if force_applied > 0:
        print(f"[{name}] 通用名后处理强制执行：{force_applied} 条")

    # ---- 合并 ----
    df_final = df_work[["名称", "频数"]].merge(
        df_std, left_on="名称", right_on="原始名称", how="left",
    )
    df_final["原始名称"] = df_final["名称"]

    # ---- 填补缺失 ----
    missing_mask = (
        df_final["通用名"].isna()
        | (df_final["通用名"].astype(str).str.strip() == "")
    )
    missing_count = missing_mask.sum()
    if missing_count > 0:
        print(f"[{name}] 警告：有 {missing_count} 行未匹配，已标记为待补充。")
        df_final.loc[missing_mask, "通用名"] = "待补充"
        df_final.loc[missing_mask, "简称/缩写"] = "LOINC ShortName Required"
        df_final.loc[missing_mask, "分类"] = "其他"
        df_final.loc[missing_mask, "映射来源"] = "未匹配"
        df_final.loc[missing_mask, "映射状态"] = "待复核"
        df_final.loc[missing_mask, "错误信息"] = "未在全局映射表中找到原始名称"
        if ADD_REVIEW_COLUMN:
            df_final.loc[missing_mask, "简称是否需复核"] = "是"

    # ---- 列顺序 ----
    columns = [
        "原始名称", "通用名", "简称/缩写", "分类",
        "标本类型", "检测属性", "采集条件", "方法学", "临床修饰",
        "LOINC编码", "LOINC映射状态", "映射来源", "映射状态",
        "冲突类型", "错误信息", "规则版本", "人工处理决定",
        "复核人", "复核日期", "复核备注",
    ]
    if KEEP_FREQ:
        columns.insert(1, "频数")
    if ADD_REVIEW_COLUMN:
        columns.append("简称是否需复核")
    for column in columns:
        if column not in df_final:
            df_final[column] = ""
    df_final = df_final[columns]

    if ADD_REVIEW_COLUMN:
        review_mask = (
            df_final["简称是否需复核"].eq("是")
            | ~df_final["映射状态"].isin(
                {"已映射", *MANUAL_RESOLVED_STATUSES}
            )
        )
        print(f"[{name}] 需复核数量：{review_mask.sum()}")

    # ---- 输出 ----
    atomic_write_excel(df_final, output_path)
    print(f"[{name}] 输出 → {output_path}")


def process_cohort(cfg: dict, dry_run: bool = False) -> None:
    """处理单个队列（独立模式，不与其他队列合并）。"""
    name = cfg["name"]
    input_path = Path(cfg["input"])
    output_path = Path(cfg["output"])
    cache_file = CACHE_FILE

    print(f"\n{'='*60}")
    print(f"队列：{name}")
    print(f"输入：{input_path}")
    print(f"输出：{output_path}")
    print(f"缓存：{cache_file}")
    print(f"{'='*60}")

    df_input = validate_input_df(read_csv_safely(input_path), name)

    if TEST_MODE:
        df_work = df_input.head(TEST_N).copy()
        print(f"当前为测试模式：只处理前 {TEST_N} 行。")
    else:
        df_work = df_input.copy()
        print("当前为全量模式：处理全部数据。")

    unique_names = df_work["名称"].drop_duplicates().tolist()
    print(f"待处理原始记录数：{len(df_work)}，唯一检验项目数：{len(unique_names)}")

    standard_map = standardize_names(unique_names, cache_file, label=name)

    df_single = pd.DataFrame(list(standard_map.values()))
    df_single = df_single.drop_duplicates(subset=["原始名称"], keep="last")
    df_single, _ = apply_manual_review(df_single, cohort_name=name)
    df_single = validate_consistency(df_single, name)
    standard_map = {
        row["原始名称"]: row
        for row in df_single.to_dict(orient="records")
    }

    if dry_run:
        print(f"[{name}] 第一阶段：缓存已积累，跳过输出。")
        return

    apply_and_output(cfg, standard_map, df_input=df_input)


def save_run_manifest(output_dir: Path, mapping_count: int) -> Path:
    """保存科研复现所需的模型、规则、Prompt和运行模式信息。"""
    suffix = "_test" if TEST_MODE else ""
    manifest_path = output_dir / f"Lab_standardization_manifest{suffix}.json"
    manifest = {
        "created_at_utc": datetime.now(timezone.utc).isoformat(),
        "base_dir": str(GLOBAL_MAP_FILE.parent.parent),
        "test_mode": TEST_MODE,
        "test_n": TEST_N if TEST_MODE else None,
        "cohorts": [cfg["name"] for cfg in COHORTS],
        "mapping_count": mapping_count,
        "model": MODEL_NAME,
        "api_base_url": API_BASE_URL,
        "rules_version": RULES_VERSION,
        "prompt_sha256": PROMPT_HASH,
        "cache_version": CACHE_VERSION,
        "manual_review_file": str(MANUAL_REVIEW_FILE),
        "manual_review_file_exists": MANUAL_REVIEW_FILE.exists(),
        "manual_review_decisions": sorted(MANUAL_REVIEW_DECISIONS),
    }
    manifest_path.parent.mkdir(parents=True, exist_ok=True)
    temp_path = manifest_path.with_suffix(manifest_path.suffix + ".tmp")
    with open(temp_path, "w", encoding="utf-8") as file:
        json.dump(manifest, file, ensure_ascii=False, indent=2)
        file.flush()
        os.fsync(file.fileno())
    temp_path.replace(manifest_path)
    return manifest_path


