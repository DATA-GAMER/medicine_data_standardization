# 候选标记必须具有队列语境：各队列的源疾病不能预测为自身共病。
SOURCE_DISEASES_BY_COHORT = {
    "CKD": {"慢性肾脏病"},
    "RA": {"类风湿关节炎"},
    "MN": {"膜性肾病"},
    "LC": {"肺恶性肿瘤"},
}


def apply_and_export(global_map, cache):
    """
    Phase 4+5：将全局映射表应用到每个队列，生成各自的 xlsx。
    """
    print(f"\n{'=' * 60}")
    print(f"Phase 4：将全局映射应用到 {len(COHORTS)} 个队列")
    print(f"{'=' * 60}")

    results = []
    for cohort in COHORTS:
        name = cohort["name"]
        input_file = Path(cohort["input"])
        output_file = Path(cohort["output"])

        df = read_table_safely(input_file)
        name_col = detect_name_column(df)
        frequency_col = detect_frequency_column(df)
        df[name_col] = df[name_col].fillna("").astype(str).str.strip()

        if TEST_MODE:
            df = df.head(TEST_N).copy()

        output_columns = ["原始诊断"]
        if frequency_col is not None:
            output_columns.append("频数")
        output_columns.extend(["标准名称", "简称", "类型", "疾病系统", "是否候选共病"])

        rows = []
        for _, source_row in df.iterrows():
            raw_name = source_row[name_col]
            frequency_value = source_row[frequency_col] if frequency_col is not None else None
            if not raw_name:
                empty_row = {
                    "原始诊断": "", "标准名称": "", "简称": "", "类型": "",
                    "疾病系统": "", "是否候选共病": "",
                }
                if frequency_col is not None:
                    empty_row["频数"] = frequency_value
                rows.append(empty_row)
                continue

            diagnoses = global_map.get(raw_name, [{
                "标准名称": raw_name, "简称": "", "类型": "其他",
                "疾病系统": "其他", "是否候选共病": "否",
            }])

            for d in diagnoses:
                output_row = {
                    "原始诊断": raw_name,
                    "标准名称": d["标准名称"],
                    "简称": d.get("简称", ""),
                    "类型": d["类型"],
                    "疾病系统": d["疾病系统"],
                    "是否候选共病": d["是否候选共病"],
                }
                if frequency_col is not None:
                    # 拆分诊断继承原组合诊断的出现频数，便于后续按标准名称聚合 Top 50。
                    output_row["频数"] = frequency_value
                rows.append(output_row)

        result_df = pd.DataFrame(rows, columns=output_columns)
        result_df = check_consistency(result_df)

        source_diseases = SOURCE_DISEASES_BY_COHORT.get(name, set())
        if source_diseases:
            source_mask = result_df["标准名称"].isin(source_diseases)
            excluded_count = int(
                (source_mask & (result_df["是否候选共病"] != "否")).sum()
            )
            result_df.loc[source_mask, "是否候选共病"] = "否"
            if excluded_count:
                print(f"  [FIX] {name}：排除源疾病候选标记 {excluded_count} 行")

        output_file.parent.mkdir(parents=True, exist_ok=True)
        exported = False
        try:
            result_df.to_excel(output_file, index=False, engine="openpyxl")
            exported = True
            print(f"  [OK] {name}：{output_file}（{len(result_df):,} 行）")
        except PermissionError:
            print(f"  [ERR] 无法写入 {output_file}，请关闭文件后重试。")

        results.append({
            "name": name,
            "input_rows": len(df),
            "output_rows": len(result_df),
            "result_df": result_df,
            "exported": exported,
        })

    # ---- 全局映射表也存为 CSV ----
    map_dir = MAP_DIR
    map_dir.mkdir(parents=True, exist_ok=True)
    map_rows = []
    for raw_name, diagnoses in global_map.items():
        for d in diagnoses:
            map_rows.append({
                "原始诊断": raw_name,
                "标准名称": d["标准名称"],
                "简称": d.get("简称", ""),
                "类型": d["类型"],
                "疾病系统": d["疾病系统"],
                "是否候选共病": d["是否候选共病"],
            })
    map_df = pd.DataFrame(map_rows, columns=["原始诊断", "标准名称", "简称", "类型", "疾病系统", "是否候选共病"])
    map_path = map_dir / "Disease_global_standard_map.csv"
    map_df.to_csv(map_path, index=False, encoding="utf-8-sig")
    print(f"\n[OK] 全局映射表：{map_path}（{len(map_df):,} 行）")

    return results


