def format_eng_abbr(name):
    """英文名→缩写：单单词直接用，多单词取首字母大写"""
    if not name:
        return ""
    name = str(name).strip()
    # 已是纯大写缩写直接返回
    if name.isupper() and len(name) <= 6 and " " not in name:
        return name
    words = name.split()
    if len(words) == 1:
        return name
    return "".join(w[0].upper() for w in words)


