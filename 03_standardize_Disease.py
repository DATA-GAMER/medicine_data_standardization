def _build_lookup_table_rows():
    """生成提示词 2.2 速查表：别名 → 标准名称（瘦身：每行最多展示少量别名）。"""
    rows = []
    for std, meta in DISEASE_RULES.items():
        aliases = [a for a in meta["aliases"] if a != std]
        if not aliases:
            continue
        shown = [a for a in aliases if not _GRADE_SUFFIX_RE.search(a)]
        if not shown:
            shown = aliases[:3]
        if len(shown) > LOOKUP_TABLE_MAX_ALIASES:
            shown = shown[:LOOKUP_TABLE_MAX_ALIASES] + [f"…等{len(aliases)}种写法"]
        rows.append(f"| {'、'.join(shown)} | {std} |")
    return "\n".join(rows)


def _build_abbr_table_rows():
    """生成提示词“六、简称”两张表。
    疾病类只保留有别名（真实数据出现）的标准——其余标准名的简称
    由 MASTER_LOOKUP 事后强制修复，模型无需背；症状类全部保留作词汇表。"""
    disease_rows, symptom_rows = [], []
    for std, meta in DISEASE_RULES.items():
        abbr = meta["简称"]
        if not abbr:
            continue
        has_alias = any(a != std for a in meta["aliases"])
        if meta["类型"] == "症状":
            symptom_rows.append(f"| {std} | {abbr} |")
        elif has_alias or not ABBR_TABLE_REQUIRE_ALIASES:
            disease_rows.append(f"| {std} | {abbr} |")
    return "\n".join(disease_rows), "\n".join(symptom_rows)


def _build_examples_text():
    """由规则表生成提示词“七、完整示例”；单条示例压缩为一行 JSON。"""
    blocks = []
    counter = [0]

    def render(input_text, std_names):
        counter[0] += 1
        diagnoses = []
        for std in std_names:
            meta = DISEASE_RULES[std]
            diagnoses.append(
                '{"标准名称":"%s","简称":"%s","类型":"%s","疾病系统":"%s","是否候选共病":"%s"}'
                % (std, meta["简称"], meta["类型"], meta["疾病系统"], meta["是否候选共病"])
            )
        if len(diagnoses) == 1:
            blocks.append(
                '### 示例 %d\n输入：%s\n输出：\n{"diagnoses":[%s]}'
                % (counter[0], input_text, diagnoses[0])
            )
        else:
            body = ",\n  ".join(diagnoses)
            blocks.append(
                '### 示例 %d\n输入：%s\n输出：\n{"diagnoses":[\n  %s\n]}'
                % (counter[0], input_text, body)
            )

    for raw in _SPLIT_EXAMPLE_KEYS:
        render(raw, SPLIT_RULES[raw])
    for raw in _EXAMPLE_SINGLES:
        entry = HARD_RULES[clean_cache_key(raw)]
        if isinstance(entry, list):
            render(raw, [e["标准名称"] for e in entry])
        else:
            render(raw, [entry["标准名称"]])
    return "\n\n".join(blocks)


