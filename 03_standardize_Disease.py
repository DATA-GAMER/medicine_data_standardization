def export_coverage_report(stats, global_map):
    """导出规则覆盖率报告与 API 处理名单，用于迭代补充 DISEASE_RULES。"""
    MAP_DIR.mkdir(parents=True, exist_ok=True)
    total = max(stats["unique_names"], 1)
    rows = [
        {"指标": "唯一原始诊断总数", "数量": stats["unique_names"], "占比": "100%"},
        {"指标": "硬性规则命中", "数量": stats["hard_hits"],
         "占比": f"{stats['hard_hits'] / total:.1%}"},
        {"指标": "缓存命中", "数量": stats["cache_hits"],
         "占比": f"{stats['cache_hits'] / total:.1%}"},
        {"指标": "API 标准化", "数量": stats["api_items"],
         "占比": f"{stats['api_items'] / total:.1%}"},
        {"指标": "API 失败", "数量": stats["failed_items"],
         "占比": f"{stats['failed_items'] / total:.1%}"},
    ]
    report_df = pd.DataFrame(rows)
    report_path = MAP_DIR / "Disease_rule_coverage_report.csv"
    report_df.to_csv(report_path, index=False, encoding="utf-8-sig")

    failed_set = set(stats["failed_names"])
    review_rows = []
    for raw in stats["api_handled_names"]:
        status = "失败" if raw in failed_set else "成功"
        for d in global_map.get(raw, []):
            review_rows.append({
                "原始诊断": raw,
                "状态": status,
                "标准名称": d["标准名称"],
                "简称": d.get("简称", ""),
                "类型": d["类型"],
                "疾病系统": d["疾病系统"],
                "是否候选共病": d["是否候选共病"],
            })
    review_df = pd.DataFrame(
        review_rows,
        columns=["原始诊断", "状态", "标准名称", "简称", "类型", "疾病系统", "是否候选共病"],
    )
    review_path = MAP_DIR / "Disease_api_names_review.csv"
    review_df.to_csv(review_path, index=False, encoding="utf-8-sig")

    print(f"\n[OK] 覆盖率报告：{report_path}")
    print(f"[OK] API 处理名单：{review_path}（{len(review_df):,} 行）")
    print("  提示：把高频的“原始诊断→标准名称”补进 DISEASE_RULES 的 aliases，下次运行即零 API 命中。")


