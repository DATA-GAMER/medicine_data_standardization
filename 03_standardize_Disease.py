def read_table_safely(file_path):
    file_path = Path(file_path)
    if not file_path.exists():
        raise FileNotFoundError(f"输入文件不存在：{file_path}")

    suffix = file_path.suffix.lower()
    if suffix == ".csv":
        last_error = None
        for encoding in ["utf-8-sig", "utf-8", "gbk", "gb18030"]:
            try:
                return pd.read_csv(file_path, encoding=encoding, low_memory=False)
            except UnicodeDecodeError as e:
                last_error = e
        raise ValueError(
            f"无法识别 CSV 编码：{file_path}\n最后错误：{last_error}"
        )

    if suffix in [".xlsx", ".xls"]:
        return pd.read_excel(file_path)

    raise ValueError(f"不支持的文件格式：{suffix}")


def detect_name_column(df):
    exact_names = [
        "原始诊断", "诊断名称", "疾病名称", "原始名称",
        "病名", "诊断", "疾病", "名称", "原始诊断名称",
    ]
    for candidate in exact_names:
        if candidate in df.columns:
            return candidate

    for col in df.columns:
        col_text = str(col).strip()
        if any(kw in col_text for kw in ["诊断", "疾病", "病名", "名称"]):
            return col
        if any(kw in col_text.lower() for kw in ["diagnosis", "disease", "name"]):
            return col

    raise ValueError(f"未识别到诊断名称列。字段：{list(df.columns)}")


def detect_frequency_column(df):
    """识别可选频数列；没有频数列时返回 None。"""
    exact_names = ["频数", "次数", "数量", "计数", "count", "frequency"]
    normalized_columns = {str(col).strip().lower(): col for col in df.columns}
    for candidate in exact_names:
        matched = normalized_columns.get(candidate.lower())
        if matched is not None:
            return matched
    return None


