def build_batch_prompt(raw_names):
    """构建批量提示词，并真正复用单条提示词中的完整医学规则。"""
    if not raw_names:
        raise ValueError("批量提示词至少需要一条原始诊断。")

    marker = "\n---\n\n现在处理原始诊断："
    full_single_prompt = build_prompt("__BATCH_PLACEHOLDER__")
    shared_rules, separator, _ = full_single_prompt.rpartition(marker)
    if not separator:
        raise RuntimeError("无法从单条提示词中提取共享规则。")

    indexed_inputs = [
        {"index": i, "原始诊断": name}
        for i, name in enumerate(raw_names, 1)
    ]
    response_example = {
        "results": [
            {
                "index": 1,
                "diagnoses": [
                    {
                        "标准名称": "高血压",
                        "简称": "HTN",
                        "类型": "疾病",
                        "疾病系统": "心血管系统",
                        "是否候选共病": "是",
                    }
                ],
            }
        ]
    }

    return f"""{shared_rules}

---

现在进行批量处理。上面的医学标准化规则全部适用，但最外层输出格式改为 results。

输入列表：
{json.dumps(indexed_inputs, ensure_ascii=False, indent=2)}

批量返回结构示例（仅展示结构）：
{json.dumps(response_example, ensure_ascii=False, indent=2)}

硬性要求：
- results 必须恰好包含 {len(raw_names)} 个元素。
- index 必须覆盖 1 到 {len(raw_names)}，每个 index 只能出现一次，顺序可任意。
- 每个元素必须包含非空 diagnoses 数组；拆分出的每个独立诊断各占一个元素。
- 不得省略任何输入，不得输出示例占位符，不要输出 Markdown 或解释文本。

只返回一个合法 JSON 对象。"""


def normalize_diagnosis_record(item):
    """清洗一条诊断，并用 MASTER_LOOKUP 修复已知标准名称的元数据。"""
    if not isinstance(item, dict):
        raise ValueError("diagnoses 中的元素必须是 JSON 对象。")

    std_name = clean_model_value(item.get("标准名称", ""))
    if not std_name:
        raise ValueError("diagnoses 中存在空的标准名称。")

    abbr = clean_model_value(item.get("简称", ""))
    abbr = format_eng_abbr(abbr) if abbr else get_abbreviation(std_name)
    diagnosis = {
        "标准名称": std_name,
        "简称": abbr,
        "类型": normalize_type(item.get("类型", "其他")),
        "疾病系统": normalize_category(item.get("疾病系统", "其他")),
        "是否候选共病": normalize_comorbidity(item.get("是否候选共病", "否")),
    }

    reference = lookup_master(std_name)
    if reference:
        for field in ["简称", "类型", "疾病系统", "是否候选共病"]:
            if reference.get(field):
                diagnosis[field] = reference[field]

    return diagnosis


def parse_batch_response(data, pending):
    """严格解析单条或批量返回；缺项、重复项和空结果均触发整批重试。"""
    if not isinstance(data, dict):
        raise ValueError("API 返回的 JSON 顶层必须是对象。")

    if "results" in data:
        raw_results = data["results"]
    elif len(pending) == 1 and "diagnoses" in data:
        raw_results = [{"index": 1, "diagnoses": data["diagnoses"]}]
    else:
        raise ValueError("API 返回缺少 results，且不是合法的单条 diagnoses 格式。")

    if not isinstance(raw_results, list) or not raw_results:
        raise ValueError("results 必须是非空数组。")

    parsed_by_index = {}
    for result_item in raw_results:
        if not isinstance(result_item, dict):
            raise ValueError("results 中的元素必须是 JSON 对象。")

        idx = result_item.get("index")
        if isinstance(idx, str) and idx.strip().isdigit():
            idx = int(idx.strip())
        if isinstance(idx, bool) or not isinstance(idx, int):
            raise ValueError(f"无效的 index：{idx!r}")
        if idx < 1 or idx > len(pending):
            raise ValueError(f"index 超出范围：{idx}")
        if idx in parsed_by_index:
            raise ValueError(f"index 重复：{idx}")

        raw_diagnoses = result_item.get("diagnoses")
        if not isinstance(raw_diagnoses, list) or not raw_diagnoses:
            raise ValueError(f"index={idx} 的 diagnoses 为空或格式错误。")
        parsed_by_index[idx] = [
            normalize_diagnosis_record(diagnosis)
            for diagnosis in raw_diagnoses
        ]

    expected_indices = set(range(1, len(pending) + 1))
    actual_indices = set(parsed_by_index)
    if actual_indices != expected_indices:
        missing = sorted(expected_indices - actual_indices)
        extra = sorted(actual_indices - expected_indices)
        raise ValueError(f"批量结果索引不完整：缺失={missing}，多余={extra}")

    return {
        pending[idx - 1]: parsed_by_index[idx]
        for idx in range(1, len(pending) + 1)
    }


def get_standard_diagnoses_batch(raw_names, cache):
    """批量处理诊断，返回结果、是否调用 API、失败的原始诊断列表。"""
    results = {}
    pending = []

    # 先检查缓存和硬性规则
    for raw_name in raw_names:
        hard = apply_hard_rules(raw_name)
        if hard:
            results[raw_name] = hard
            continue
        cache_key = clean_cache_key(raw_name)
        if USE_CACHE and cache_key in cache:
            item = cache[cache_key]
            if isinstance(item, list) and len(item) > 0:
                try:
                    diagnoses = [normalize_diagnosis_record(d) for d in item]
                    results[raw_name] = diagnoses
                    continue
                except (TypeError, ValueError, AttributeError) as e:
                    print(f"    [WARN] 缓存条目无效，将重新请求：{raw_name}（{e}）")
        pending.append(raw_name)

    if not pending:
        return results, False, []

    # 批量调用 API
    prompt = build_batch_prompt(pending) if len(pending) > 1 else build_prompt(pending[0])
    last_error = None

    for attempt in range(1, MAX_RETRIES + 1):
        try:
            response = client.chat.completions.create(
                model=MODEL_NAME,
                messages=[
                    {
                        "role": "system",
                        "content": (
                            "你是一名严谨的临床医学术语标准化与疾病系统分类专家。"
                            "必须严格返回JSON。只返回JSON，不要任何解释文本。"
                        ),
                    },
                    {"role": "user", "content": prompt},
                ],
                temperature=0,
                stream=False,
            )

            content = response.choices[0].message.content
            data = extract_json(content)
            api_results = parse_batch_response(data, pending)

            # 整批验证通过后再一次性写入内存缓存，避免部分结果污染缓存。
            if SAVE_CACHE:
                for raw_name, diagnoses in api_results.items():
                    cache[clean_cache_key(raw_name)] = [dict(d) for d in diagnoses]
            results.update(api_results)
            return results, True, []

        except Exception as e:
            last_error = e
            print(f"    第 {attempt}/{MAX_RETRIES} 次批量请求失败：{e}")
            if attempt < MAX_RETRIES:
                time.sleep(attempt * 2)

    # 全部失败
    print(f"    [ERR] 批量请求全部重试失败：{last_error}")
    for raw_name in pending:
        results[raw_name] = [{
            "标准名称": raw_name, "简称": "",
            "类型": "其他", "疾病系统": "其他", "是否候选共病": "否",
        }]
    # 失败兜底只用于生成可检查的输出，绝不写入缓存。
    return results, True, list(pending)


def check_consistency(result_df):
    """用 MASTER_LOOKUP 自动修复所有已知条目的类型/系统/共病/简称"""
    required_columns = {"标准名称", "简称", "类型", "疾病系统", "是否候选共病"}
    missing_columns = required_columns - set(result_df.columns)
    if missing_columns:
        raise ValueError(f"一致性校验缺少字段：{sorted(missing_columns)}")
    if result_df.empty:
        print("  [WARN] 没有可校验的诊断记录")
        return result_df

    fixed = 0

    for idx in result_df.index:
        name = result_df.at[idx, "标准名称"]
        if not name or name not in MASTER_LOOKUP:
            continue
        ref = MASTER_LOOKUP[name]
        if ref["简称"] and result_df.at[idx, "简称"] != ref["简称"]:
            result_df.at[idx, "简称"] = ref["简称"]; fixed += 1
        if ref["类型"] and result_df.at[idx, "类型"] != ref["类型"]:
            result_df.at[idx, "类型"] = ref["类型"]; fixed += 1
        if ref["疾病系统"] and result_df.at[idx, "疾病系统"] != ref["疾病系统"]:
            result_df.at[idx, "疾病系统"] = ref["疾病系统"]; fixed += 1
        if ref["是否候选共病"] and result_df.at[idx, "是否候选共病"] != ref["是否候选共病"]:
            result_df.at[idx, "是否候选共病"] = ref["是否候选共病"]; fixed += 1

    # 硬性违规
    violations = ["肾透析", "血液透析", "腹膜透析", "高血压3级", "高血压病3级",
                  "CKD5期", "2型糖尿病", "脑出血后遗症", "陈旧性肺结核"]
    for v in violations:
        if v in result_df["标准名称"].values:
            print(f"  [ERR] 硬性规则违规：'{v}' 不应作为标准名称（需清缓存重跑）")

    still_other_sys = ((result_df["类型"] == "疾病") & (result_df["疾病系统"] == "其他")).sum()
    still_other_type = (result_df["类型"] == "其他").sum()
    still_missing = ((result_df["类型"].isin(["疾病", "症状"])) & (result_df["简称"] == "")).sum()

    if fixed:  print(f"  [FIX] MASTER_LOOKUP 修复 {fixed} 行")
    if still_other_sys: print(f"  [WARN] {still_other_sys} 个疾病系统='其他'（不在 MASTER_LOOKUP 中）")
    if still_other_type: print(f"  [WARN] {still_other_type} 行类型='其他'")
    if still_missing: print(f"  [WARN] {still_missing} 行简称缺失")
    if fixed == 0 and still_other_sys == 0 and still_other_type == 0 and still_missing == 0:
        print("  [OK] 一致性校验通过")

    return result_df


