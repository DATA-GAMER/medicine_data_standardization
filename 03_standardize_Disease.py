# 12. 统一标准化（Phase 1+2+3：收集→去重→标准化→校验）
# =====================================================

def build_global_standard_map(cache):
    """
    Phase 1+2+3：从所有队列收集名称 → 去重 → 统一标准化 → 自愈校验
    返回 global_map: {raw_name: [{标准名称, 简称, 类型, 疾病系统, 是否候选共病}, ...]}
    """
    # ---- Phase 1：收集所有队列的全部原始名称 ----
    all_names = set()
    for cohort in COHORTS:
        df = read_table_safely(Path(cohort["input"]))
        name_col = detect_name_column(df)
        if TEST_MODE:
            # 与 Phase 4 保持一致：每个队列都取前 TEST_N 行。
            df = df.head(TEST_N)
        names = df[name_col].fillna("").astype(str).str.strip()
        all_names.update(n for n in names if n)

    unique_names = sorted(all_names)
    print(f"\n{'=' * 60}")
    print(f"Phase 1：从 {len(COHORTS)} 个队列收集到 {len(unique_names):,} 个唯一诊断名称")
    print(f"{'=' * 60}")

    # ---- Phase 2：统一标准化 ----
    global_map = {}
    total_hard_hits = 0
    total_cache_hits = 0
    total_api_batches = 0
    total_api_items = 0
    failed_api_names = set()
    api_handled_names = set()

    batches = [unique_names[i:i + BATCH_SIZE] for i in range(0, len(unique_names), BATCH_SIZE)]
    print(f"Phase 2：开始标准化，共 {len(batches)} 批，硬性规则 {len(HARD_RULES)} 条\n")

    for bi, batch in enumerate(batches, 1):
        # 必须在调用前统计；API 成功后会更新内存缓存。
        hard_names = [n for n in batch if apply_hard_rules(n) is not None]
        cache_names = []
        pending_names = []
        for raw_name in batch:
            if raw_name in hard_names:
                continue
            cache_key = clean_cache_key(raw_name)
            item = cache.get(cache_key) if USE_CACHE else None
            try:
                if isinstance(item, list) and item:
                    [normalize_diagnosis_record(d) for d in item]
                    cache_names.append(raw_name)
                else:
                    pending_names.append(raw_name)
            except (TypeError, ValueError, AttributeError):
                pending_names.append(raw_name)

        batch_results, called_api, failed_names = get_standard_diagnoses_batch(batch, cache)

        total_hard_hits += len(hard_names)
        total_cache_hits += len(cache_names)
        global_map.update(batch_results)

        if called_api:
            total_api_batches += 1
            total_api_items += len(pending_names)
            failed_api_names.update(failed_names)
            api_handled_names.update(pending_names)
            # 每个成功批次立即原子保存，长任务中断时不会丢失此前进度。
            if SAVE_CACHE and not failed_names:
                save_cache(cache, UNIFIED_CACHE_FILE)

        if bi % max(1, len(batches) // 10) == 0 or bi == len(batches):
            pct = bi / len(batches) * 100
            print(
                f"  [{bi}/{len(batches)}] {pct:.0f}% | "
                f"硬={total_hard_hits} 缓存={total_cache_hits} "
                f"API={total_api_batches}批 失败={len(failed_api_names)}"
            )

        if called_api:
            time.sleep(SLEEP_SECONDS)

    print(
        f"\n标准完成：硬={total_hard_hits} 缓存={total_cache_hits} "
        f"API={total_api_batches}批({total_api_items}项) "
        f"失败={len(failed_api_names)}项"
    )

    # ---- Phase 3：自愈校验 ----
    print(f"\nPhase 3：全局一致性校验与自动修复...")
    # 构建临时 DataFrame 用于校验
    fields = ["标准名称", "简称", "类型", "疾病系统", "是否候选共病"]
    rows = []
    row_refs = []
    for raw_name, diagnoses in global_map.items():
        for diagnosis_index, d in enumerate(diagnoses):
            row_refs.append((raw_name, diagnosis_index))
            rows.append({
                "标准名称": d["标准名称"],
                "简称": d.get("简称", ""),
                "类型": d["类型"],
                "疾病系统": d["疾病系统"],
                "是否候选共病": d["是否候选共病"],
            })
    temp_df = pd.DataFrame(rows, columns=fields)
    temp_df = check_consistency(temp_df)

    # DataFrame 是副本，必须按原始位置显式回写 global_map。
    for (raw_name, diagnosis_index), repaired in zip(
        row_refs, temp_df.to_dict(orient="records")
    ):
        global_map[raw_name][diagnosis_index] = {
            field: repaired[field] for field in fields
        }

    # 同步修复后的结果到缓存；失败兜底和硬性规则不写入缓存。
    if SAVE_CACHE:
        for raw_name, diagnoses in global_map.items():
            if raw_name in failed_api_names or apply_hard_rules(raw_name) is not None:
                continue
            cache[clean_cache_key(raw_name)] = [dict(d) for d in diagnoses]
        save_cache(cache, UNIFIED_CACHE_FILE)
        print(f"全局缓存已保存：{UNIFIED_CACHE_FILE}（{len(cache):,} 条）")

    return global_map, {
        "unique_names": len(unique_names),
        "hard_hits": total_hard_hits,
        "cache_hits": total_cache_hits,
        "api_batches": total_api_batches,
        "api_items": total_api_items,
        "failed_items": len(failed_api_names),
        "failed_names": sorted(failed_api_names),
        "api_handled_names": sorted(api_handled_names),
    }


