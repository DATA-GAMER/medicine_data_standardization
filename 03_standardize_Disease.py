def _rules_hash_file(cache_file):
    """规则指纹旁车文件：不改变缓存 JSON 格式，兼容旧版缓存。"""
    return Path(str(cache_file) + ".rules_hash.txt")


def load_cache(cache_file):
    cache_file = Path(cache_file)
    hash_file = _rules_hash_file(cache_file)
    if CLEAR_CACHE_BEFORE_RUN and cache_file.exists():
        cache_file.unlink()
        hash_file.unlink(missing_ok=True)
        print("  已清空旧缓存（含规则指纹）。")
        return {}
    if not cache_file.exists():
        print("  未发现统一缓存，将创建新缓存。")
        return {}
    try:
        with open(cache_file, "r", encoding="utf-8") as f:
            cache = json.load(f)
        if not isinstance(cache, dict):
            print("  缓存格式异常，重新创建。")
            return {}
        print(f"  已加载统一缓存，共 {len(cache):,} 条记录。")

        # ---- 规则版本校验：规则变化时自动修复受影响条目 ----
        old_hash = hash_file.read_text(encoding="utf-8").strip() if hash_file.exists() else ""
        if old_hash != RULES_FINGERPRINT:
            if not old_hash:
                print(f"  [WARN] 缓存没有规则指纹（旧版缓存），当前规则版本：{RULES_FINGERPRINT}")
            else:
                print(f"  [WARN] 规则已变化：缓存版本 {old_hash} → 当前 {RULES_FINGERPRINT}")
            repaired = dropped = 0
            for key, item in list(cache.items()):
                if key in HARD_RULES:
                    # 硬性规则优先于缓存，这类条目已无意义，直接清除。
                    cache.pop(key, None)
                    dropped += 1
                    continue
                if not isinstance(item, list) or not item:
                    cache.pop(key, None)
                    dropped += 1
                    continue
                try:
                    fixed = [normalize_diagnosis_record(d) for d in item]
                except (TypeError, ValueError, AttributeError):
                    cache.pop(key, None)
                    dropped += 1
                    continue
                if fixed != item:
                    cache[key] = fixed
                    repaired += 1
            if repaired or dropped:
                print(f"  [FIX] 按新规则修复 {repaired} 条、清除 {dropped} 条缓存（硬规则已覆盖/无效）。")
            else:
                print("  [OK] 缓存条目与新规则一致，无需修复。")
        else:
            print(f"  [OK] 规则版本一致（{RULES_FINGERPRINT}），缓存可直接复用。")
        return cache
    except Exception as e:
        print(f"  读取缓存失败，重新创建：{e}")
        return {}


def save_cache(cache, cache_file):
    cache_file = Path(cache_file)
    cache_file.parent.mkdir(parents=True, exist_ok=True)
    tmp = cache_file.with_suffix(cache_file.suffix + ".tmp")
    with open(tmp, "w", encoding="utf-8") as f:
        json.dump(cache, f, ensure_ascii=False, indent=2)
    tmp.replace(cache_file)
    # 记录产生该缓存的规则版本，供下次运行时联动校验
    _rules_hash_file(cache_file).write_text(RULES_FINGERPRINT, encoding="utf-8")


