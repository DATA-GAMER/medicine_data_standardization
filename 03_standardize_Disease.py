def extract_json(content):
    if not isinstance(content, str):
        raise ValueError("API 返回内容不是字符串。")
    content = content.strip()
    m = re.search(r"```(?:json)?\s*(.*?)\s*```", content, flags=re.S | re.I)
    if m:
        content = m.group(1).strip()
    m = re.search(r"\{.*\}", content, flags=re.S)
    if not m:
        raise ValueError(f"未发现 JSON：{content[:500]}")
    return json.loads(m.group(0).strip())


def clean_model_value(value):
    if value is None:
        return ""
    return str(value).strip().strip(' \t\r\n"\'"''。；;，,：:')


def normalize_category(cat):
    cat = clean_model_value(cat)
    if cat in CATEGORY_ALIASES:
        cat = CATEGORY_ALIASES[cat]
    return cat if cat in VALID_CATEGORIES else "其他"


def normalize_type(t):
    t = clean_model_value(t)
    if t in TYPE_ALIASES:
        t = TYPE_ALIASES[t]
    return t if t in VALID_TYPES else "其他"


def normalize_comorbidity(val):
    val = clean_model_value(val)
    return "是" if val in ("是", "yes", "true", "1") else "否"


