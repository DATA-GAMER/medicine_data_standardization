def _build_hard_rules():
    """由 DISEASE_RULES + SPLIT_RULES 自动生成 HARD_RULES；冲突立即报错。"""
    rules = {}

    def add(key, entry):
        key = clean_cache_key(key)
        if not key:
            raise ValueError("HARD_RULES 出现空键")
        if key in rules and rules[key] != entry:
            raise ValueError(f"HARD_RULES 键冲突：{key!r}\n  旧={rules[key]}\n  新={entry}")
        rules[key] = entry

    # 1) 别名规则（一个别名 → 一条标准诊断）
    for std, meta in DISEASE_RULES.items():
        single = _make_hard_entry(
            std, meta["简称"], meta["类型"], meta["疾病系统"], meta["是否候选共病"]
        )
        for alias in meta["aliases"]:
            add(alias, dict(single))

    # 2) 标准名称自身兜底（标准名精确出现也直接命中，零 API）；
    #    别名规则优先，因此“终末期肾病→尿毒症”等映射不会被自身兜底覆盖。
    for std, meta in DISEASE_RULES.items():
        key = clean_cache_key(std)
        if key not in rules:
            rules[key] = _make_hard_entry(
                std, meta["简称"], meta["类型"], meta["疾病系统"], meta["是否候选共病"]
            )

    # 3) 拆分规则（一条原始诊断 → 多条标准诊断）
    for raw, std_names in SPLIT_RULES.items():
        entries = []
        for std in std_names:
            meta = DISEASE_RULES[std]  # KeyError 说明 SPLIT_RULES 引用了不存在的标准名
            entries.append(_make_hard_entry(
                std, meta["简称"], meta["类型"], meta["疾病系统"], meta["是否候选共病"]
            ))
        add(raw, entries)

    return rules


HARD_RULES = _build_hard_rules()


